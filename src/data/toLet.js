export function buildInitialToLetListings(customers, toLetListings) {
  return [
    ...toLetListings.map((listing, index) => ({
      id: listing.id,
      title: listing.title,
      ownerName: listing.owner,
      ownerPhone: listing.phone,
      ownerCustomerId: customers.find((customer) => customer.phone === listing.phone)?.id || null,
      area: listing.area,
      propertyType: listing.type,
      rent: listing.rent,
      deposit: listing.rent * 2,
      maintenance: index === 0 ? 1500 : 800,
      postedAt: listing.postedAt,
      approvedAt: listing.id === 'TL-001' ? '2026-04-04' : listing.id === 'TL-003' ? '2026-03-22' : null,
      approvalStatus: listing.status === 'Pending' ? 'Pending' : 'Approved',
      description: listing.id === 'TL-001'
        ? 'Well-maintained apartment with modular kitchen, wardrobe, and immediate move-in option.'
        : listing.id === 'TL-002'
          ? 'Owner submitted semi-furnished family apartment awaiting review and approval.'
          : 'Compact bachelor-friendly flat close to transport and local stores.',
      bedrooms: listing.type === '3BHK' ? 3 : listing.type === '2BHK' ? 2 : 1,
      bathrooms: listing.type === '3BHK' ? 2 : 1,
      furnishing: listing.furnished ? 'Fully Furnished' : 'Semi Furnished',
      parking: listing.id === 'TL-003' ? 'No parking' : 'Open parking',
      sizeSqft: listing.type === '3BHK' ? 1450 : listing.type === '2BHK' ? 1100 : 580,
      tenantPreference: listing.id === 'TL-003' ? 'Bachelors' : 'Family',
      petsAllowed: listing.id !== 'TL-003',
      location: listing.id === 'TL-001'
        ? { lat: 17.7278, lng: 83.3045 }
        : listing.id === 'TL-002'
          ? { lat: 17.7231, lng: 83.3012 }
          : { lat: 17.7731, lng: 83.3712 },
      locationAccuracy: listing.id === 'TL-002' ? 'Approx' : 'Verified',
      directCallAllowed: listing.id !== 'TL-002',
      photos: listing.id === 'TL-002' ? ['Front View', 'Hall View'] : ['Front View', 'Bedroom', 'Kitchen'],
      enquiries: listing.enquiries,
      trialExtensionDays: 0,
      manualStatus: null,
    })),
    ...TOLET_EXTRA_LISTINGS,
  ].map((listing) => ({
    ...listing,
    ownerCustomerId: listing.ownerCustomerId || customers.find((customer) => customer.phone === listing.ownerPhone)?.id || null,
  }))
}